"""
Example Plugin: Data Export

Export chromatin structure data to various formats.
"""

from uchrom.plugins import UChromPlugin
import pandas as pd
import numpy as np


class DataExportPlugin(UChromPlugin):
    """
    Export chromatin structure data to various formats.

    Supports CSV, PDB, and custom formats.
    """

    def __init__(self):
        super().__init__()
        self.name = "DataExport"
        self.version = "1.0.0"
        self.description = "Export data to various formats"

    def analyze(self, chromdata, format="csv", **kwargs):
        """
        Export data to specified format.

        Parameters
        ----------
        chromdata : ChromData
            Input chromatin structure data
        format : str
            Export format: "csv", "pdb", "json"

        Returns
        -------
        dict
            Export information and data
        """
        if format == "csv":
            return self._export_csv(chromdata)
        elif format == "pdb":
            return self._export_pdb(chromdata)
        elif format == "json":
            return self._export_json(chromdata)
        else:
            raise ValueError(f"Unsupported format: {format}")

    def _export_csv(self, chromdata):
        """Export to CSV format."""
        df = chromdata.to_dataframe()
        csv_data = df.to_csv(index=False)
        return {
            "format": "csv",
            "data": csv_data,
            "n_rows": len(df),
            "columns": df.columns.tolist(),
        }

    def _export_pdb(self, chromdata):
        """Export to PDB format."""
        coords = chromdata.coords
        spots = chromdata.spots

        pdb_lines = ["HEADER    CHROMATIN STRUCTURE"]
        pdb_lines.append("REMARK   Generated by U-Chrom DataExport Plugin")

        for i, (coord, spot) in enumerate(zip(coords, spots.itertuples()), start=1):
            # PDB ATOM format
            # ATOM serial name altLoc resName chainID resSeq iCode x y z occupancy tempFactor element charge
            line = (
                f"ATOM  {i:5d}  CA  GLY A{i:4d}    "
                f"{coord[0]:8.3f}{coord[1]:8.3f}{coord[2]:8.3f}"
                f"  1.00  0.00           C  "
            )
            pdb_lines.append(line)

        pdb_lines.append("END")
        pdb_data = "\n".join(pdb_lines)

        return {
            "format": "pdb",
            "data": pdb_data,
            "n_atoms": len(coords),
        }

    def _export_json(self, chromdata):
        """Export to JSON format."""
        import json

        data = {
            "coords": chromdata.coords.tolist(),
            "spots": chromdata.spots.to_dict(orient="records"),
            "n_spots": len(chromdata.coords),
        }

        if chromdata.cells is not None:
            data["cells"] = chromdata.cells.to_dict(orient="records")

        json_data = json.dumps(data, indent=2)

        return {
            "format": "json",
            "data": json_data,
            "n_spots": len(chromdata.coords),
        }

    def visualize(self, result, **kwargs):
        """
        No visualization for export plugin.
        """
        return None
